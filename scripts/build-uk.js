// Builds uk/index.html: the same page with Ukrainian text already in the HTML,
// so search engines and AI crawlers can read the Ukrainian version.
// Run: node scripts/build-uk.js   (no dependencies; the deploy workflow runs it too)
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const SITE = "https://wisely-applied-ai.com";
let html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const js = fs.readFileSync(path.join(root, "assets/js/site.js"), "utf8");

// 1. Ukrainian dictionary from site.js (const UK = {...}; plus later Object.assign(UK, {...}); blocks)
const start = js.indexOf("const UK = {");
const end = js.indexOf("\n};", start);
if (start < 0 || end < 0) throw new Error("UK dictionary not found in site.js");
const UK = vm.runInNewContext("(" + js.slice(start + "const UK = ".length, end + 2) + ")");
let from = 0;
for (;;) {
  const a = js.indexOf("Object.assign(UK, {", from);
  if (a < 0) break;
  const b = js.indexOf("\n});", a);
  Object.assign(UK, vm.runInNewContext("(" + js.slice(a + "Object.assign(UK, ".length, b + 2) + ")"));
  from = b;
}

// 2. Replace the inner HTML of every element with data-i="key"
function replaceInner(src) {
  const re = /<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*\sdata-i="([^"]+)"[^>]*>/g;
  const hits = [];
  let m;
  while ((m = re.exec(src))) hits.push({ tag: m[1].toLowerCase(), key: m[2], open: m.index, innerStart: m.index + m[0].length });
  let missing = [];
  for (let i = hits.length - 1; i >= 0; i--) {
    const h = hits[i];
    if (!(h.key in UK)) { missing.push(h.key); continue; }
    const tagRe = new RegExp("<(/?)" + h.tag + "\\b[^>]*>", "gi");
    tagRe.lastIndex = h.innerStart;
    let depth = 1, t, closeAt = -1;
    while ((t = tagRe.exec(src))) {
      if (t[0].endsWith("/>")) continue;
      depth += t[1] ? -1 : 1;
      if (depth === 0) { closeAt = t.index; break; }
    }
    if (closeAt < 0) throw new Error("No closing tag for data-i=" + h.key);
    src = src.slice(0, h.innerStart) + UK[h.key] + src.slice(closeAt);
  }
  if (missing.length) console.warn("No Ukrainian text for:", [...new Set(missing)].join(", "));
  return src;
}
html = replaceInner(html);

// 3. Head: language, title, description, URLs
const rep = (from, to) => {
  if (!html.includes(from)) throw new Error("Not found in index.html: " + from);
  html = html.replace(from, to);
};
const ukTitle = "WAAI · Wisely Applied AI: фреймворк зрілості ШІ, консалтинг і навчання";
const ukDesc = "WAAI (Wisely Applied AI, мудре застосування ШІ) — відкритий фреймворк для впровадження ШІ в організаціях: модель зрілості ШІ з 5 рівнів, ролі й правила, консалтинг, корпоративне навчання та оцінка зрілості ШІ.";
const ukShort = "Відкрита методологія для організацій, де люди й ШІ працюють разом.";
html = html.replace(/<html lang="en">/, '<html lang="uk">');
html = html.replace(/<title>[^<]*<\/title>/, "<title>" + ukTitle + "</title>");
html = html.replace(/<meta name="description" content="[^"]*">/, '<meta name="description" content="' + ukDesc + '">');
html = html.replace(/<meta property="og:title" content="[^"]*">/, '<meta property="og:title" content="WAAI · Wisely Applied AI · Мудре застосування ШІ">');
html = html.replace(/<meta property="og:description" content="[^"]*">/, '<meta property="og:description" content="' + ukShort + '">');
html = html.replace(/<meta name="twitter:description" content="[^"]*">/, '<meta name="twitter:description" content="' + ukShort + '">');
rep('<meta property="og:url" content="' + SITE + '/">', '<meta property="og:url" content="' + SITE + '/uk/">');
rep('<link rel="canonical" href="' + SITE + '/">', '<link rel="canonical" href="' + SITE + '/uk/">');
rep('<meta property="og:locale" content="en_GB">\n<meta property="og:locale:alternate" content="uk_UA">',
    '<meta property="og:locale" content="uk_UA">\n<meta property="og:locale:alternate" content="en_GB">');
html = html.replace('<button type="button" id="lang-uk" aria-pressed="false">', '<button type="button" id="lang-uk" aria-pressed="true">');
html = html.replace('<button type="button" id="lang-en" aria-pressed="true">', '<button type="button" id="lang-en" aria-pressed="false">');

// 4. The page lives one folder down: make local links root-relative
html = html.replace(/(\s(?:src|href))="(assets\/|contact\.php)/g, '$1="/$2');

// 5. Team photo alt text in Ukrainian
for (const k of ["tm1", "tm2", "tm3"]) {
  const en = { tm1: "Iryna Kriuchkova", tm2: "Nadiya Trub", tm3: "Nati Nazar" }[k];
  html = html.split('alt="' + en + '"').join('alt="' + UK[k] + '"');
}

fs.mkdirSync(path.join(root, "uk"), { recursive: true });
fs.writeFileSync(path.join(root, "uk/index.html"),
  "<!-- Generated by scripts/build-uk.js from index.html and assets/js/site.js. Do not edit by hand. -->\n" + html);
console.log("uk/index.html written");
